"""外の世界から「仕組みの一文」を採る。

`concepts` が裸の語（改札、回覧板、検針）だと、出てくるのは

    改札のやり方を通知に持ち込む。見るのは待ち時間。

で止まる。**どのやり方かは書いていない**ので、読み手が全部補うことになる。
持ってくるべきなのは語ではなく、何をどうしているかが名指しされた一文:

    改札は、通れなかった人を後ろに溜めず、脇へ出して個別に捌く。
    通知で同じことをするなら、何が要る?

ここはその一文を文章から抜く部分。**LLM は使わない**（キー無しで動くのが
Phase 1 からの方針）。手掛かりは意味ではなく**文の形**に置く:

- 構造の印 —「〜ではなく〜」「〜せずに〜」「〜ことで〜」「まず〜次に〜」。
  仕組みの説明は、何かと引き比べるか、手段と目的を結ぶ形になりやすい
- 操作の動詞 —「捌く」「防ぐ」「戻す」「分ける」。やり方を持っている文は
  必ず何かを操作している

**片方だけでは足りない。** 「〜ことで知られている」は構造の印を持つが操作が
無く、「ゴミを出す」は操作だけで仕組みを説明していない。両方を要求する。

落とすものも形で決まる:

- 定義文（「Xとは〜である」）— 分類は仕組みではない
- 指示語で始まる文（「これは〜」「その際〜」）— 前の文が無いと読めない
- 年号や数字の羅列 — 沿革であって仕組みではない
- 体言止め・名付け・伝聞・評価で終わる文 — やり方ではなく、やり方に
  ついて何かを言っている
- 目的だけの文（「〜を防ぐために使われる」）— どうやるかが無い

**規則を合わせた文章で測った precision は当てにならない。** 日本語
Wikipedia の 133 記事で規則を足して 95% まで上げたあと、別の 191 記事に
当てると 64% だった。そこでも規則を足し、さらに別の 106 記事で規則を
固定して測ると 79%（33 件中 26 件）。**残りの 2 割は形では落とせない**——
主語が前の文にある、手段を「工夫」「方法」とだけ言う、といった文で、
通った一文は人が読んでから使う（`data/mechanisms.yaml` はそうして選んだ）。
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

#: 仕組みの一文として短すぎる／長すぎる境界（文字数）。
#: 短い文は「〜を行う」で終わって中身が無く、長い文はテンプレートに
#: 差し込むと読めない。**手で書いた良い例は 26〜31 字**だったので、
#: そこを基準に取る（90 字まで許すと、節が4つある文が通ってしまった）。
MIN_LEN = 20
MAX_LEN = 60

#: 読点の数の上限。節が多い文は、長さが収まっていても読めない。
#: 長さより効く——「〜し、さらに〜して、〜ている」は字数が足りていても
#: 一息で読めない。
MAX_CLAUSES = 2

#: 構造の印。仕組みの説明は、引き比べるか、手段と目的を結ぶ。
_STRUCTURE = re.compile(
    r"ではなく"
    r"|ではなしに"
    r"|せずに"
    r"|ずに済"
    # 「ということで」は談話、「〜のことで」は定義、「〜ことで知られる」は評判。
    # どれも手段の「ことで」ではない。
    r"|(?<!という)(?<!の)ことで(?!知られ|有名|も知られ)"
    r"|ことによ(?:り|って)"
    r"|目的で、"
    r"|ようにして"
    r"|代わりに"
    r"|まず.{0,40}(?:次に|その後|そのあと|最後に)"
    # 「〜アリのように、」は喩えであって目的ではない。
    r"|ために、|(?<!の)よう(?:に)?、"
)

#: 操作の動詞。**やり方を持っている文は必ず何かを操作している。**
#: 「ある」「なる」「言う」のような状態や言及の動詞は入れない。
_OPERATION = re.compile(
    r"捌(?:く|き|いて)"
    r"|防(?:ぐ|ぎ|いで)"
    r"|戻(?:す|し|して)"
    r"|(?<!引き)分(?:ける|け|けて)"
    r"|減ら(?:す|し|して)"
    r"|増や(?:す|し|して)"
    r"|早め(?:る|て)"
    r"|遅ら(?:せる|せ|せて)"
    r"|選(?:ぶ|び|んで)"
    r"|並べ(?:る|て)"
    r"|入れ替え(?:る|て)"
    r"|省(?:く|き|いて)"
    r"|溜め(?:る|て)"
    r"|流(?:す|し|して)"
    r"|配(?:る|り|って)"
    r"|束ね(?:る|て)"
    r"|切り替え(?:る|て)"
    r"|止め(?:る|て)"
    r"|保(?:つ|ち|って)"
    r"|(?<![一-龥])回(?:す|し|して)"
    r"|置き換え(?:る|て)"
    r"|待(?:つ|ち|って)"
    r"|知らせ(?:る|て)"
    r"|取り除(?:く|き|いて)"
    r"|割り当て(?:る|て)"
    r"|打ち切(?:る|り|って)"
    r"|使い回(?:す|し|して)"
)

#: 操作の動詞（広いほう）。Wikipedia の本文で「構造の印はあるが操作の動詞が
#: 無い」で落ちた 253 文を読むと、本物の仕組み文が大量に混ざっていた
#: （「脱穀ドラムを回転させることにより〜」「ボタンを押すことで〜」）。
#: 上の一覧は手元の文章から作ったので、機械や道具の動きを持っていなかった。
#:
#: - 使役の「させる」—「回転させる」「変化させる」。何かに何かをさせるのは操作
#: - 手や機械の動き — 押す、通す、開ける、載せる、調節する
#:
#: **連用形の「し」は入れない。**「押し寿司」「通し番号」が動詞として拾われる。
_OPERATION_WIDE = re.compile(
    r"させ(?:る|て|、)"
    r"|押(?:す|して)"
    r"|送(?:る|って)"
    r"|通(?:す|して)"
    r"|変え(?:る|て)"
    r"|上げ(?:る|て)"
    r"|下げ(?:る|て)"
    r"|調[節整](?:する|し|して)"
    r"|配置(?:する|し|して)"
    r"|設置(?:する|し|して)"
    r"|設け(?:る|て)"
    r"|固定(?:する|し|して)"
    r"|交換(?:する|し|して)"
    r"|組み合わせ(?:る|て)"
    r"|開(?:く|ける|いて|けて)"
    r"|閉(?:じる|じて|める|めて)"
    r"|載せ(?:る|て)"
    r"|抑え(?:る|て)"
    r"|集め(?:る|て)"
    r"|運(?:ぶ|んで)"
    r"|積(?:む|んで)"
    r"|隠(?:す|して)"
    r"|広げ(?:る|て)"
    r"|狭め(?:る|て)"
    r"|外(?:す|して)"
    r"|逃が(?:す|して)"
    r"|つな(?:ぐ|いで)"
    r"|混ぜ(?:る|て)"
    r"|重ね(?:る|て)"
    r"|冷や(?:す|して)"
    r"|温め(?:る|て)"
    r"|測(?:る|って)"
    r"|詰め(?:る|て)"
    r"|沈め(?:る|て)"
    r"|刻(?:む|んで)"
    r"|裏返(?:す|して)"
    r"|絞(?:る|って)"
    r"|伸ば(?:す|して)"
    r"|縮め(?:る|て)"
    r"|揃え(?:る|て)"
    r"|囲(?:む|んで)"
    r"|覆(?:う|って)"
    r"|塞(?:ぐ|いで)"
    r"|遮(?:る|って)"
)

#: 目的を名指しする形。「〜を防ぐため」「〜を保つために」。
#: **「ため」だけを印にしてはいけない。** 理由の「ため」（「〜であるため、
#: 需要を保っている」）が大量に通る。Wikipedia の本文で測ると、操作の動詞に
#: 直に付く「ため」は 12 件中 10 件が本物、「ため」全部だと 30 件中 11 件だった。
#:
#: **広いほうの動詞には付けない。**「回復させるために使用される」
#: 「周知させるための広報活動を行っている」は何のためかを言うだけで、
#: どうやるかが無い（7 件中 3 件が偽）。
_PURPOSE = re.compile(rf"(?:{_OPERATION.pattern})ため")

#: 目的だけを言って、手段が無い。「〜を防ぐために使われる」「〜を防ぐため
#: 設けられている」は**何のためにあるか**であって、どうやるかではない。
#: 「〜を防ぐために白色度の低い紙が用いられる」は手段を名指ししているので
#: 通す——「ため」の直後に「使う」「設ける」が来るものだけを落とす。
_PURPOSE_ONLY = re.compile(
    r"ため(?:に)?、?(?:使|利用|用い|使用|設け|設置|作ら|造ら|開発|考案|導入)"
)

#: 定義文。分類を述べているだけで、やり方が無い。
_DEFINITION = re.compile(
    r"(?:とは|、)[^。]{0,60}(?:である|です|のことで|の一種|を指す)"
    # 文の途中の「であり、」「であるが、」と、文末の「の一つ」。
    # 「〜で発音する鍵盤楽器であり、パイプオルガンとも呼ばれる」は分類。
    r"|であ(?:り|るが)、|の(?:一つ|ひとつ)$"
    # 「Xとは、〜容器」。述語を省いた定義は「である」を持たない。
    r"|^[^、]{1,25}とは、"
    # 名付けの文。「〜の部分を閘門閾と呼ぶ」「〜は海岸堤防とよばれる」は
    # 呼び名を教えているだけ。**やり方を述べたあとに呼び名で終わる本物も
    # 落ちる**（「超音波を止めることで〜「シカに優しい踏切」と呼ばれている」）。
    # 3 件の偽に対して本物 1 件だったので、落とす側に倒した。
    r"|と(?:も)?(?:呼ぶ|呼ばれる|呼ばれた|呼ばれている|よばれる|称する|称される)$"
    r"|と(?:いい|呼び|称し)、"
    # 「XはYである」で終わる文。述べているのは分類で、動きではない。
    r"|(?:である|であった|だった)$"
    r"|種類(?:が|も)ある$"
)

#: 文の途中の「前に書いたとおり」。出だしの指示語と同じく、前の文が無いと
#: 読めない（「同様の作業をハンドルを回すことで行う」——何の作業かが無い）。
_BACK_REFERENCE = re.compile(
    r"同様の|前述|上述|先述|上記|後述|下記|以下の|次のよう|[こそ]のよう"
    r"|図[0-9０-９A-Za-z中]|これら|この(?:部分|状態|場合|方法|方式|とき|際|ため)"
)

#: 括弧が閉じていない、または括弧で終わる。句点が括弧の中にあると文がそこで
#: 割れて、「エアポンプの一種）にて火薬を…」のような切れ端になる。
_BRACKET_PAIRS = (("（", "）"), ("(", ")"), ("「", "」"), ("『", "』"))

#: 見込みや伝聞で終わる文。やり方ではなく、やり方への評価を述べている。
#: 「〜という」「〜らしい」「〜と報告されている」も同じ。書き手が見たやり方
#: ではなく、誰かがそう言っているという話。
_HEARSAY_END = re.compile(
    r"(?:期待され|見込まれ|予想され|報告され|考えられ|とされ|といわれ|と言われ)"
    r"(?:る|ている)$"
    r"|(?:という|らしい)$"
)

#: 前の文が無いと読めない出だし。単独で出すと意味が通らない。
_ANAPHORA = re.compile(
    r"^(?:これ|それ|その|この|こう|そう|また|さらに"
    r"|同様|一方|他方|そのため|したがって|なお|すなわち|つまり"
    r"|ただし|但し|あるいは|もしくは|しかし|だが|例えば|たとえば|いずれ"
    r"|よって|そこで|逆に|特に、|例外として|そして|彼|当時)"
)

#: 体言止め。述語が無いので「Xは、〜」に差し込むと文にならない。
#: 実文で「作業量を増やすことではなく、プロダクトを良くすること」が通った。
#: 構造の印も操作の動詞も持っているが、**やり方ではなく価値の表明**で、
#: 差し込むと「改札は、〜こと」になって壊れる。
#:
#: **漢字や片仮名で終わる文も同じ。** 日本語の述語は平仮名で終わるので、
#: 「〜を防ぐために加熱・殺菌した保存食」「〜を知らせるための表示灯」は
#: 名詞で止まっている。語を列挙するより、文字の種類で見るほうが漏れない。
_NOMINAL_END = re.compile(
    r"(?:こと|もの|ところ|ため|点|の|とき|場合|形)$|[一-龥ァ-ヶーA-Za-z0-9０-９]$"
)

#: 規範や評価で終わる文。「〜してはならない」「〜が望ましい」「〜ことがある」は
#: やり方を述べているのではなく、やり方について何かを言っている。
_VERDICT_END = re.compile(
    r"(?:てはならない|べきである|必要がある|必要となる|必要になる"
    r"|ことがある|場合(?:が|も)ある|好ましい|好ましくない|望ましい"
    r"|重要(?:である|となる|になる)|わけではない"
    # 「〜を防ぐための機構はない」。無いことを述べている。
    r"|[はがも]ない)$"
)

#: 手段を指しているが名指ししていない。「様々な方法が用いられ」
#: 「多くの戦略が実施されている」は、どのやり方かを言っていない。
_UNNAMED_MEANS = re.compile(
    r"(?:様々な|さまざまな|多くの|いくつかの|各種の|種々の)"
    r"(?:方法|戦略|工夫|対策|手段|方式|技術)"
)

#: ラベル付きの断片。記録や表の1行は「見出し: 中身」の形になり、
#: 文のように見えて文ではない（実文で lessons の記録が1件通った）。
#:
#: 箇条書きの「項目 - 説明」も同じ。空白を落とすと「石岡大火-被害の拡大を…」
#: になり、項目名が文の頭に貼り付く。
_LABELLED = re.compile(r"[:：]|(?<=[ぁ-んァ-ヶー一-龥])[-‐–](?=[ぁ-んァ-ヶ一-龥「])")

#: 文の途中の空白。日本語の文は語の間を空けないので、仮名や漢字の間の
#: 空白は**項目名と説明の境目**（「分相ガラス 特定のガラスにおいて…」）。
#: 空白を落としてからでは見えないので、落とす前の文で見る。
_INNER_SPACE = re.compile(r"[ぁ-んァ-ヶー一-龥][ 　\t]+[ぁ-んァ-ヶ一-龥]")

#: 沿革。年月日や数字が多い文は仕組みではない。
_DIGITS = re.compile(r"[0-9０-９]")
MAX_DIGITS = 6

#: 出典の脚注。本文に混ざると文末が壊れる。
_FOOTNOTE = re.compile(r"\[\s*\d+\s*\]|\[(?:要出典|誰|いつ)[^\]]*\]")

#: 括弧の中の読みや原語。仕組みの説明には要らないので落とす。
_PARENS = re.compile(r"[（(][^（()）]{0,40}[)）]")


@dataclass(frozen=True)
class Mechanism:
    """外の世界の、名指しできる仕組み。

    `subject` が「何の」、`how` が「どうしているか」。出典を持たせるのは、
    刺さったときにユーザーが自分で辿れるようにするため。
    """

    #: 何の仕組みか（記事の題など）。
    subject: str
    #: 何をどうしているか。そのまま文中に差し込める一文。
    how: str
    #: どこから採ったか。URL でも書名でもよい。
    source: str = ""
    #: 分野タグ。遠さの計算に使う。
    domains: tuple[str, ...] = field(default=())


def _clean(sentence: str) -> str:
    """文から、仕組みの説明に要らないものを落とす。"""
    sentence = _FOOTNOTE.sub("", sentence)
    sentence = _PARENS.sub("", sentence)
    return re.sub(r"\s+", "", sentence).strip("。 　")


#: 散文ではない行。見出し・箇条書き・表・コードは仕組みの説明ではない。
_NOT_PROSE = re.compile(
    r"^\s*(?:#{1,6}\s|[-*+]\s|\||>|```|~~~|\d+\.\s"
    # Wikipedia の本文の見出し（== 構造 ==）。空行を挟まずに本文が続くので、
    # 落とさないと「===血管因子===末梢の血管が…」と文の頭に貼り付く。
    r"|={2,}[^=\n]+={2,}\s*$)"
)

#: 折り返しではない短い行の境界。段落の途中の行がこれより短く（一番長い行の
#: 半分未満）、句点で終わっていなければ、それは折り返された文の一部ではなく
#: **項目の名前**。Wikipedia の本文は「熱放射を防ぐ」「高接ぎ」のような
#: 項目名の行の直後に説明の行が来るので、繋ぐと名前が文の頭に貼り付く。
_LABEL_RATIO = 0.5


def split_sentences(text: str) -> list[str]:
    """文に割る。

    **行で先に割ってはいけない。** Markdown も Wikipedia の本文も1文が複数行に
    折り返されるので、行で割ると文が途中で切れる。実際、手元の散文に当てたとき
    唯一通った一文が「〜弱かった——「給水塔にあって」という断片だった。

    空行を段落の区切りとして、段落の中の改行は繋ぐ。そのうえで「。」で割る。
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    out: list[str] = []
    for block in re.split(r"\n\s*\n", text):
        lines = [
            line.strip()
            for line in block.split("\n")
            if line.strip() and not _NOT_PROSE.match(line)
        ]
        if not lines:
            continue
        widest = max(len(line) for line in lines)
        runs: list[str] = [""]
        for index, line in enumerate(lines):
            runs[-1] += line
            is_label = (
                index < len(lines) - 1
                and not line.endswith("。")
                and len(line) < widest * _LABEL_RATIO
            )
            if is_label or line.endswith("。"):
                runs.append("")
        for run in runs:
            for piece in re.split(r"(?<=。)", run):
                piece = piece.strip()
                if piece:
                    out.append(piece)
    return out


def reject_reason(sentence: str) -> str | None:
    """落とす理由。通るなら None。

    **どの条件で落ちたかを数えられるようにしておく。** 取れ高が低いとき、
    絞りすぎている条件がどれかは、理由を数えないと分からない。新しい
    採取元に当てるたびにここを見る。
    """
    body = _clean(sentence)
    if len(body) < MIN_LEN:
        return "短すぎる"
    if len(body) > MAX_LEN:
        return "長すぎる"
    if body.count("、") > MAX_CLAUSES:
        return "節が多い"
    if _ANAPHORA.match(body):
        return "指示語で始まる"
    if _LABELLED.search(body) or _INNER_SPACE.search(_PARENS.sub("", sentence).strip()):
        return "ラベル付き"
    if body.endswith(("）", ")", "」", "』")) or any(
        body.count(left) != body.count(right) for left, right in _BRACKET_PAIRS
    ):
        return "括弧が閉じていない"
    if _NOMINAL_END.search(body):
        return "体言止め"
    if len(_DIGITS.findall(body)) > MAX_DIGITS:
        return "数字が多い"
    if _DEFINITION.search(body):
        return "定義文"
    if _BACK_REFERENCE.search(body):
        return "前の文を指している"
    if _HEARSAY_END.search(body):
        return "見込みで終わる"
    if _VERDICT_END.search(body):
        return "規範や評価で終わる"
    if _UNNAMED_MEANS.search(body):
        return "手段を名指ししていない"
    if _PURPOSE_ONLY.search(body):
        return "目的だけで手段が無い"
    if not (_STRUCTURE.search(body) or _PURPOSE.search(body)):
        return "構造の印が無い"
    if not (_OPERATION.search(body) or _OPERATION_WIDE.search(body)):
        return "操作の動詞が無い"
    return None


def looks_like_mechanism(sentence: str) -> bool:
    """その一文が「やり方を名指ししている」か。

    **意味は見ない。形だけで決める。** 構造の印と操作の動詞の両方を要求し、
    定義・指示語・沿革を落とす。取れ高は下がるが、混ざるほうが困る——
    ここを通った一文は、そのままユーザーの目に入る。
    """
    return reject_reason(sentence) is None


def extract(
    subject: str,
    text: str,
    *,
    source: str = "",
    domains: tuple[str, ...] = (),
    limit: int = 3,
) -> list[Mechanism]:
    """一つの文章から、仕組みの一文を取り出す。

    同じ記事から何本も採ると偏るので、既定では上位 `limit` 本だけ。
    順番は文章に出てきた順（前のほうが概説で、仕組みの核に近いことが多い）。
    """
    found: list[Mechanism] = []
    seen: set[str] = set()
    for sentence in split_sentences(text):
        # **文として閉じていないものは出さない。** 段落の末尾や箇条書きの
        # 途中は句点で終わらない断片になり、そのまま差し込むと途切れる。
        if not sentence.rstrip().endswith("。"):
            continue
        if not looks_like_mechanism(sentence):
            continue
        body = _clean(sentence)
        if body in seen:
            continue
        seen.add(body)
        found.append(
            Mechanism(subject=subject, how=body, source=source, domains=domains)
        )
        if len(found) >= limit:
            break
    return found
